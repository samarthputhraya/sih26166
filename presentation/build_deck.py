# "multi-modal" and "cross-sensor" were banned for the college round, when no such real pair
# existed. Real visible<->infrared (Kaguya MI, IIRS) and OHRC<->NAC rows exist since 18 Sep, so
# the words are allowed - but never next to MiLOI or fore/aft, which are the SAME sensor.
BANNED = ("<", "Your Team Name", "Idea submission", "62,519", "43.9", "0.7 px",
          "cross sensor", "SNPSU LunaX", "TITLE PAGE", "IDEA TITLE", "TBD")
SAME_SENSOR_WORDS = ("MiLOI", "fore vs aft", "fore/aft", "NAC pairs")
# Words of ours per content slide, diagram labels included. Slide 4 is a scorecard and a
# risk -> strategy map, so it carries more labels than prose; slide 6 is references.
MAX_WORDS = {2: 230, 3: 195, 4: 330, 5: 230}      # v9 as built after its claim-check: a guard, not a target


def _ours(slide):
    return [sh for sh in slide.shapes if sh.name.startswith("lx ")]


def _audit_deck(deck) -> list[str]:
    """Everything about the built file that a machine can check, checked on every run."""
    bad: list[str] = []
    if len(deck.slides) != 6:
        bad.append(f"slide count is {len(deck.slides)}, must be 6 including the title page")

    band_l, band_r, band_b = 0.30, 12.79, 6.88
    for i, slide in enumerate(deck.slides, 1):
        ours = _ours(slide)
        for sh in ours if i > 1 else []:
            l, r = Emu(sh.left).inches, Emu(sh.left).inches + Emu(sh.width).inches
            b = Emu(sh.top).inches + Emu(sh.height).inches
            if l < 0.54 - 1e-6 or r > band_r + 1e-6:
                bad.append(f"slide {i}: {sh.name} spans {l:.2f}..{r:.2f} in, outside the "
                           f"0.54..{band_r:.2f} in content band")
            if b > band_b + 1e-6:
                bad.append(f"slide {i}: {sh.name} reaches {b:.2f} in, into the footer bar's margin")
        if i == 1:
            for sh in ours:
                if Emu(sh.left).inches < band_l:
                    bad.append(f"slide 1: {sh.name} starts left of the metadata block")

        # A picture must not share space with any other shape of ours.
        pics = [sh for sh in ours if sh.shape_type == 13]
        for pic in pics:
            pl, pr = Emu(pic.left).inches, Emu(pic.left).inches + Emu(pic.width).inches
            pt_, pb = Emu(pic.top).inches, Emu(pic.top).inches + Emu(pic.height).inches
            for o in ours:
                if o is pic:
                    continue
                ol, orr = Emu(o.left).inches, Emu(o.left).inches + Emu(o.width).inches
                ot, ob = Emu(o.top).inches, Emu(o.top).inches + Emu(o.height).inches
                if pl < orr - 0.01 and ol < pr - 0.01 and pt_ < ob - 0.01 and ot < pb - 0.01:
                    if not (o.name == "lx repo-card"):          # the QR sits on its card
                        bad.append(f"slide {i}: {pic.name} overlaps {o.name}")

        for sh in ours:
            if not sh.has_text_frame:
                continue
            for p in sh.text_frame.paragraphs:
                for r in p.runs:
                    rPr = r._r.find(qn("a:rPr"))
                    faces = {t: (rPr.find(qn(f"a:{t}")).get("typeface")
                                 if rPr is not None and rPr.find(qn(f"a:{t}")) is not None
                                 else None)
                             for t in ("latin", "ea", "cs")}
                    if set(faces.values()) != {BODY_FONT}:
                        bad.append(f"slide {i}: run {r.text[:28]!r} has fonts {faces} - a "
                                   f"missing ea/cs face sends ° and × through font linking")
                    if r.font.size is not None and r.font.size.pt < 9:
                        bad.append(f"slide {i}: run {r.text[:28]!r} is {r.font.size.pt} pt, "
                                   f"below the 9 pt floor")

        text = " ".join(sh.text_frame.text for sh in slide.shapes if sh.has_text_frame)
        for word in BANNED:
            if word in text:
                bad.append(f"slide {i}: banned text {word!r} is on the slide")
        for sent in re.split(r"(?<=[.;])\s+", text):
            if any(w in sent for w in SAME_SENSOR_WORDS) and re.search(
                    r"cross-sensor|multi-modal", sent, re.I):
                bad.append(f"slide {i}: same-sensor pair called cross-sensor/multi-modal: "
                           f"{sent[:60]!r}")
        # Provenance: "in REPORT.md AT commit X" says X's tree contains a report holding these
        # figures. Verify the claim if it is made, rather than banning the words.
        for m in re.finditer(r"REPORT\.md[^.]{0,40}?at\s+(?:the\s+\w+[- ]\w+\s+)?commit\s+"
                             r"`?([0-9a-f]{7,40})`?", text, re.I):
            sha = m.group(1)
            got = subprocess.run(["git", "show", f"{sha}:REPORT.md"],
                                 cwd=str(HERE.parent), capture_output=True, text=True)
            missing = [f for f in ("13.1 km", "0.57 m", "8.2 s", "160 distinct")
                       if f not in got.stdout]
            if got.returncode or missing:
                bad.append(f"slide {i}: claims its figures are in REPORT.md at commit {sha}, "
                           f"but that commit's REPORT.md is missing {missing or 'itself'}. "
                           f"Say 'measured at' - the report is regenerated after the freeze")
        n_words = sum(len(sh.text_frame.text.split()) for sh in ours if sh.has_text_frame)
        if n_words > MAX_WORDS.get(i, 10 ** 6):
            bad.append(f"slide {i}: {n_words} words of ours, over its {MAX_WORDS[i]} cap")

    all_text = " ".join(sh.text_frame.text for s in deck.slides for sh in s.shapes
                        if sh.has_text_frame)
    for need in (TEAM_ID, TEAM_NAME, "SIH26166", "160 distinct ground windows",
                 "8 instrument pairings"):
        if need not in all_text:
            bad.append(f"{need!r} does not appear anywhere in the deck")
    for s in list(deck.slides)[1:]:
        if _pointer_box(s) is not None:
            bad.append("a template pointer box is still on a content slide")
    return bad


def _check_pointers(template, deck) -> bool:
    """Every template pointer is on its slide as a heading of its own, in the template's words.

    A pointer line is accepted verbatim, or without a trailing parenthetical of examples -
    "Technologies to be used (e.g. programming languages, frameworks, hardware)" -> "Technologies
    to be used". Nothing else is: no rewording, no reordering of words, no abbreviation.
    """
    ok = True
    for i in range(1, 6):
        pb = _pointer_box(template.slides[i])
        want = [_norm(p.text) for p in pb.text_frame.paragraphs if p.text.strip()]
        have = {_norm(sh.text_frame.text) for sh in deck.slides[i].shapes if sh.has_text_frame}
        for w in want:
            short = re.sub(r"\s*\([^)]*\)\s*$", "", w)
            if w not in have and short not in have:
                print(f"  !! slide {i + 1}: pointer not present as a heading: {w[:70]!r}")
                ok = False
    return ok


def build() -> int:
    if not TEMPLATE.exists():
        print(f"missing {TEMPLATE} - download the official template first")
        return 2
    prs = Presentation(str(TEMPLATE))
    slide1(prs.slides[0])

    words = {}
    for idx, draw in SLIDE_BUILDERS.items():
        slide = prs.slides[idx - 1]

        # The template's oval is a placeholder for the team name; fill it, keep its style.
        oval = _team_oval(slide)
        if oval is not None:
            paras = oval.text_frame.paragraphs
            first = paras[0]
            if first.runs:
                first.runs[0].text = TEAM_NAME
                _set_run_font(first.runs[0])
                for r in first.runs[1:]:
                    r.text = ""
            else:
                first.text = TEAM_NAME
            for p in paras[1:]:
                p._p.getparent().remove(p._p)

        ft = _footer(slide)
        if ft is not None:
            ft.text_frame.clear()
            ft.text_frame.paragraphs[0].add_run().text = ""

        # The pointer prompts become our heading tabs; the prompt box itself goes.
        pb = _pointer_box(slide)
        if pb is not None:
            pb._element.getparent().remove(pb._element)
        if idx == 2:
            _set_slide2_title(slide)

        draw(slide)
        words[idx] = sum(len(sh.text_frame.text.split()) for sh in _ours(slide)
                         if sh.has_text_frame)

    _delete_slide(prs, 6)          # the instructions slide, which itself says we may
    prs.save(str(OUT))

    deck = Presentation(str(OUT))
    pointers_ok = _check_pointers(Presentation(str(TEMPLATE)), deck)
    problems = _audit_deck(deck)
    print(f"  wrote {OUT.name}  ({OUT.stat().st_size:,} bytes, {len(deck.slides)} slides)")
    print("  words of ours per slide: " + " · ".join(f"s{k}={v}" for k, v in sorted(words.items())))
    print(f"  every pointer present as a heading: {'YES' if pointers_ok else 'NO'}")
    if problems:
        print(f"  AUDIT: {len(problems)} problem(s)")
        for line in problems:
            print(f"    !! {line}")
    else:
        print("  AUDIT: clean - geometry, fonts, type floor, banned terms, pointers, provenance")
    print("  NEXT: python -m presentation.export_pdf  (the portal accepts PDF only)")
    return 0 if (pointers_ok and not problems) else 1


if __name__ == "__main__":
    raise SystemExit(build())
