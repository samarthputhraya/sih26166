_FONT_FILES = {False: "C:/Windows/Fonts/calibri.ttf", True: "C:/Windows/Fonts/calibrib.ttf"}
_font_cache: dict = {}


def _text_width_in(text: str, size_pt: float, bold: bool) -> float:
    """Width of one line of Calibri in inches - measured, so tabs and chips fit their words."""
    key = (bold, size_pt)
    if key not in _font_cache:
        try:
            _font_cache[key] = ImageFont.truetype(_FONT_FILES[bold], int(round(size_pt * 10)))
        except OSError:
            _font_cache[key] = None
    f = _font_cache[key]
    if f is None:                                    # no Calibri on this machine: estimate
        return len(text) * size_pt * (0.55 if bold else 0.5) / 72
    return f.getlength(text) / 10 / 72


def _set_run_font(run, name=BODY_FONT):
    """Name the font for the latin, East Asian and complex-script ranges of one run.

    `run.font.name` writes only <a:latin>. Leaving <a:ea>/<a:cs> to be inherited from a theme
    that declares them empty is what sent ° and × through East-Asian font linking. Element
    order inside <a:rPr> is fixed by the schema: latin, then ea, then cs.
    """
    run.font.name = name
    rPr = run._r.get_or_add_rPr()
    for tag in ("a:ea", "a:cs"):
        for el in list(rPr.findall(qn(tag))):
            rPr.remove(el)
    after = rPr.find(qn("a:latin"))
    for tag in ("a:ea", "a:cs"):
        el = rPr.makeelement(qn(tag), {"typeface": name})
        if after is not None:
            after.addnext(el)
        else:
            rPr.append(el)
        after = el


def _set_bullet(para, char, mar_l, indent):
    """A real PowerPoint bullet with a hanging indent (or buNone), never a typed "•"."""
    pPr = para._p.get_or_add_pPr()
    pPr.set("marL", str(int(Inches(mar_l))))
    pPr.set("indent", str(int(Inches(indent))))
    for tag in ("a:buNone", "a:buChar", "a:buAutoNum", "a:buFont"):
        for el in list(pPr.findall(qn(tag))):
            pPr.remove(el)
    new = ([pPr.makeelement(qn("a:buNone"), {})] if char is None
           else [pPr.makeelement(qn("a:buFont"), {"typeface": BODY_FONT}),
                 pPr.makeelement(qn("a:buChar"), {"char": char})])
    anchor = pPr.find(qn("a:defRPr"))
    for el in new:
        if anchor is not None:
            anchor.addprevious(el)
        else:
            pPr.append(el)


def R(text, size, bold=False, colour=INK, italic=False):
    """One run: (text, size pt, bold, colour, italic)."""
    return (text, size, bold, colour, italic)


def P(*runs, align="l", sb=0, sa=0, ls=1.0):
    """One paragraph of runs."""
    return {"runs": runs, "align": align, "sb": sb, "sa": sa, "ls": ls}


_ALIGN = {"l": PP_ALIGN.LEFT, "c": PP_ALIGN.CENTER, "r": PP_ALIGN.RIGHT}
_ANCHOR = {"t": MSO_ANCHOR.TOP, "m": MSO_ANCHOR.MIDDLE, "b": MSO_ANCHOR.BOTTOM}


def _fill_text(tf, paras, anchor="t", margins=(0.06, 0.03, 0.06, 0.03)):
    tf.word_wrap = True
    tf.auto_size = MSO_AUTO_SIZE.NONE
    tf.vertical_anchor = _ANCHOR[anchor]
    tf.margin_left, tf.margin_top, tf.margin_right, tf.margin_bottom = (Inches(m) for m in margins)
    for i, p in enumerate(paras):
        para = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        _set_bullet(para, None, 0.0, 0.0)
        para.alignment = _ALIGN[p["align"]]
        para.line_spacing = p["ls"]
        para.space_before = Pt(p["sb"])
        para.space_after = Pt(p["sa"])
        for text, size, bold, colour, italic in p["runs"]:
            run = para.add_run()
            run.text = text
            run.font.size = Pt(size)
            run.font.bold = bold
            run.font.italic = italic
            run.font.color.rgb = colour
            _set_run_font(run)


def _strip_style(shape):
    st = shape._element.find(qn("p:style"))
    if st is not None:
        shape._element.remove(st)


def _box(slide, x, y, w, h, paras=(), fill=None, line=None, lw=0.75, kind=MSO_SHAPE.ROUNDED_RECTANGLE,
         radius=0.10, anchor="m", margins=(0.08, 0.04, 0.08, 0.04), name="box"):
    """A shape with optional text. radius is the corner as a fraction of the shorter side."""
    sh = slide.shapes.add_shape(kind, Inches(x), Inches(y), Inches(w), Inches(h))
    sh.name = f"lx {name}"
    _strip_style(sh)
    if kind == MSO_SHAPE.ROUNDED_RECTANGLE:
        sh.adjustments[0] = radius
    if fill is None:
        sh.fill.background()
    else:
        sh.fill.solid()
        sh.fill.fore_color.rgb = fill
    if line is None:
        sh.line.fill.background()
    else:
        sh.line.color.rgb = line
        sh.line.width = Pt(lw)
    _fill_text(sh.text_frame, paras, anchor, margins)
    return sh


def _text(slide, x, y, w, h, paras, anchor="t", margins=(0.0, 0.0, 0.0, 0.0), name="text"):
    tb = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tb.name = f"lx {name}"
    _fill_text(tb.text_frame, paras, anchor, margins)
    return tb


def _arrow(slide, x1, y1, x2, y2, colour=MUTED, w=1.5):
    c = slide.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, Inches(x1), Inches(y1),
                                   Inches(x2), Inches(y2))
    c.name = "lx arrow"
    _strip_style(c)
    c.line.color.rgb = colour
    c.line.width = Pt(w)
    ln = c.line._get_or_add_ln()
    ln.append(ln.makeelement(qn("a:tailEnd"), {"type": "triangle", "w": "med", "len": "med"}))
    return c


def _tab(slide, x, y, text, colour=BLUE, size=11.5, h=0.30):
    """A pointer heading: a home-plate tab in the footer's blue, sized to its words."""
    w = _text_width_in(text, size, True) + 0.42
    _box(slide, x, y, w, h, [P(R(text, size, True, WHITE))], fill=colour,
         kind=MSO_SHAPE.PENTAGON, anchor="m", margins=(0.12, 0.0, 0.16, 0.0), name="tab")
    return w


def _pic(slide, name, x, y, w=None, h=None, border=None):
    path = FIGURES / name
    if not path.is_file():
        print(f"  !! figure missing: {path.name} - run `python -m presentation.make_figures`")
        return None
    with Image.open(path) as im:
        wp, hp = im.size
    if w is None:
        w = h * wp / hp
    if h is None:
        h = w * hp / wp
    pic = slide.shapes.add_picture(str(path), Inches(x), Inches(y), Inches(w), Inches(h))
    pic.name = f"lx pic {name}"
    if border is not None:
        pic.line.color.rgb = border
        pic.line.width = Pt(0.75)
    return pic


def _dot(slide, x, y, d, colour):
    return _box(slide, x, y, d, d, fill=colour, kind=MSO_SHAPE.OVAL, name="dot")


