def _pointer_box(slide):
    for sh in slide.shapes:
        if (sh.has_text_frame and not sh.is_placeholder and not sh.name.startswith("lx ")
                and any(m in sh.text_frame.text for m in POINTER_MARKERS)):
            return sh
    return None


def _team_oval(slide):
    for sh in slide.shapes:
        if sh.has_text_frame and sh.text_frame.text.strip() == "Your Team Name":
            return sh
    return None


def _footer(slide):
    for sh in slide.shapes:
        if sh.has_text_frame and "Idea submission" in sh.text_frame.text:
            return sh
    return None


def _set_slide2_title(slide):
    """The title placeholder read "IDEA TITLE" - a label for the idea's own title. Filled."""
    t = slide.shapes.title
    tf = t.text_frame
    for p in list(tf.paragraphs)[1:]:
        p._p.getparent().remove(p._p)
    para = tf.paragraphs[0]
    for child in list(para._p):
        if child.tag in (qn("a:r"), qn("a:br")):
            para._p.remove(child)
    para.line_spacing = 0.9
    for k, line in enumerate(IDEA_TITLE_LINES):
        if k:
            para.add_line_break()
        run = para.add_run()
        run.text = line
        run.font.size = Pt(28)
        run.font.bold = True
        run.font.color.rgb = INK
        _set_run_font(run, TITLE_FONT)


def _delete_slide(prs, index):
    xml_slides = prs.slides._sldIdLst
    slides = list(xml_slides)
    rId = slides[index].get(
        "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id")
    prs.part.drop_rel(rId)
    xml_slides.remove(slides[index])


def _norm(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


